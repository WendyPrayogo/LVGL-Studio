import React, { useState } from 'react';
import { ProjectData } from '../types/lvgl';
import {
  generateUiH,
  generateUiC,
  generateUiEventsC,
  generateArduinoMain,
  generatePlatformIoIni,
  generatePartitionsCsvFile,
} from '../utils/lvglCodeGen';
import JSZip from 'jszip';
import {
  Code2,
  X,
  Copy,
  Check,
  Download,
  FolderArchive,
  FileText,
  Terminal,
} from 'lucide-react';

interface CodeExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  project: ProjectData;
  onUpdateLvglVersion: (version: 'v8' | 'v9') => void;
}

type TabType = 'ui.h' | 'ui.c' | 'ui_events.c' | 'main.ino' | 'platformio.ini' | 'partitions.csv';

export const CodeExportModal: React.FC<CodeExportModalProps> = ({
  isOpen,
  onClose,
  project,
  onUpdateLvglVersion,
}) => {
  const [activeTab, setActiveTab] = useState<TabType>('ui.c');
  const [copied, setCopied] = useState(false);
  const [isZipping, setIsZipping] = useState(false);

  if (!isOpen) return null;

  // Generate code files dynamically based on project state
  const uiH = generateUiH(project);
  const uiC = generateUiC(project);
  const uiEventsC = generateUiEventsC(project);
  const mainIno = generateArduinoMain(project);
  const platformioIni = generatePlatformIoIni(project);
  const partitionsCsv = generatePartitionsCsvFile(project);

  const getActiveCode = (): string => {
    switch (activeTab) {
      case 'ui.h':
        return uiH;
      case 'ui.c':
        return uiC;
      case 'ui_events.c':
        return uiEventsC;
      case 'main.ino':
        return mainIno;
      case 'platformio.ini':
        return platformioIni;
      case 'partitions.csv':
        return partitionsCsv;
      default:
        return uiC;
    }
  };

  const activeCode = getActiveCode();

  const handleCopy = () => {
    navigator.clipboard.writeText(activeCode);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadSingle = () => {
    const blob = new Blob([activeCode], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = activeTab;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleDownloadZip = async () => {
    setIsZipping(true);
    try {
      const zip = new JSZip();

      // Folder structure
      const srcFolder = zip.folder('src');
      srcFolder?.file('ui.h', uiH);
      srcFolder?.file('ui.c', uiC);
      srcFolder?.file('ui_events.c', uiEventsC);

      zip.file('platformio.ini', platformioIni);
      zip.file(`${project.name.toLowerCase().replace(/[^a-z0-9_]/g, '_')}.ino`, mainIno);
      zip.file('partitions.csv', partitionsCsv);

      const readme = `# ${project.name}
Generated by LVGL GUI Generator for Embedded Systems

Target Hardware:
- Microcontroller:  ${project.display.mcu.toUpperCase()}
- LCD Controller:   ${project.display.lcdType.toUpperCase()}
- Port Interface:   ${project.display.port}
- Flash Memory:     ${project.display.flashConfig.flashSize} (${project.display.flashConfig.flashMode.toUpperCase()} @ ${project.display.flashConfig.flashSpeed})
- External PSRAM:   ${project.display.flashConfig.psram}
- Partition Scheme: ${project.display.flashConfig.partitionScheme}
Display Resolution: ${project.display.width}x${project.display.height}
Color Depth: ${project.display.colorDepth}-bit RGB
LVGL Version: ${project.display.lvglVersion.toUpperCase()}

## Files Included
- \`src/ui.h\`: UI component pointers struct, function prototypes, and event callbacks.
- \`src/ui.c\`: Complete LVGL object instantiation, styles, geometries, and parenting.
- \`src/ui_events.c\`: Implementation hooks for event callbacks to connect with hardware GPIOs, sensors, and relays.
- \`platformio.ini\`: PlatformIO build flags, flash size, PSRAM flags, and library dependencies.
- \`partitions.csv\`: Custom flash partition table for Arduino / PlatformIO.
- \`main.ino\`: Complete Arduino sketch with display driver flush callback and main loop.

## Quick Start
1. Open this directory in VS Code with the PlatformIO extension, or open the \`.ino\` in Arduino IDE.
2. Install the **lvgl** library (v${project.display.lvglVersion === 'v8' ? '8.3.x' : '9.x'}) and your display driver library (e.g. TFT_eSPI or LovyanGFX).
3. Connect your board via USB and flash!
`;
      zip.file('README.md', readme);

      const content = await zip.generateAsync({ type: 'blob' });
      const url = URL.createObjectURL(content);
      const a = document.createElement('a');
      a.href = url;
      a.download = `${project.name.toLowerCase().replace(/[^a-z0-9_]/g, '_')}_lvgl_${project.display.lvglVersion}.zip`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    } catch (err) {
      console.error('Failed to create ZIP', err);
    } finally {
      setIsZipping(false);
    }
  };

  const tabs: { key: TabType; label: string; icon: string }[] = [
    { key: 'ui.h', label: 'ui.h', icon: 'h' },
    { key: 'ui.c', label: 'ui.c', icon: 'c' },
    { key: 'ui_events.c', label: 'ui_events.c', icon: 'c' },
    { key: 'main.ino', label: 'main.ino (Arduino)', icon: 'ino' },
    { key: 'platformio.ini', label: 'platformio.ini', icon: 'ini' },
    { key: 'partitions.csv', label: 'partitions.csv', icon: 'csv' },
  ];

  return (
    <div className="fixed inset-0 z-50 bg-black/75 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="w-full max-w-5xl h-[88vh] bg-slate-900 border border-slate-800 rounded-xl shadow-2xl flex flex-col overflow-hidden text-slate-100">
        {/* Header */}
        <div className="px-6 py-3.5 border-b border-slate-800 flex items-center justify-between shrink-0 bg-slate-950/60">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-cyan-500/10 border border-cyan-500/20 flex items-center justify-center text-cyan-400">
              <Code2 className="w-4 h-4" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-sm font-bold text-white">Generated Embedded LVGL C/C++ Code</h3>
                <span className="text-[11px] font-mono text-cyan-400 bg-cyan-950/60 border border-cyan-800/60 px-2 py-0.5 rounded">
                  {project.display.mcu.toUpperCase()} · {project.display.lcdType.toUpperCase()} ({project.display.width}×{project.display.height}) · {project.display.touchConfig?.type !== 'none' ? `TOUCH: ${project.display.touchConfig?.type.toUpperCase()}` : 'NO TOUCH'}
                </span>
              </div>
              <p className="text-xs text-slate-400">
                Ready-to-compile modular source files for Arduino, ESP-IDF, PlatformIO, STM32Cube, and Zephyr.
              </p>
            </div>
          </div>

          {/* Right actions & LVGL version toggle */}
          <div className="flex items-center gap-3">
            {/* Version Toggle */}
            <div className="flex items-center bg-slate-950 p-0.5 rounded-lg border border-slate-800">
              <button
                onClick={() => onUpdateLvglVersion('v8')}
                className={`px-2.5 py-1 text-xs font-mono font-medium rounded ${
                  project.display.lvglVersion === 'v8'
                    ? 'bg-slate-800 text-cyan-400 shadow-sm'
                    : 'text-slate-400 hover:text-slate-200'
                }`}
              >
                LVGL v8
              </button>
              <button
                onClick={() => onUpdateLvglVersion('v9')}
                className={`px-2.5 py-1 text-xs font-mono font-medium rounded ${
                  project.display.lvglVersion === 'v9'
                    ? 'bg-slate-800 text-cyan-400 shadow-sm'
                    : 'text-slate-400 hover:text-slate-200'
                }`}
              >
                LVGL v9
              </button>
            </div>

            <button
              onClick={onClose}
              className="text-slate-400 hover:text-white p-1 rounded-md hover:bg-slate-800"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Tab Strip & Actions */}
        <div className="px-6 py-2 border-b border-slate-800 bg-slate-950/40 flex items-center justify-between shrink-0 overflow-x-auto">
          <div className="flex items-center gap-1.5">
            {tabs.map((tab) => (
              <button
                key={tab.key}
                onClick={() => setActiveTab(tab.key)}
                className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-mono transition-colors ${
                  activeTab === tab.key
                    ? 'bg-slate-800 text-cyan-300 font-semibold border border-slate-700'
                    : 'text-slate-400 hover:text-slate-200 hover:bg-slate-800/40'
                }`}
              >
                <FileText className="w-3.5 h-3.5 text-slate-500" />
                <span>{tab.label}</span>
              </button>
            ))}
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-300 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg transition-colors border border-slate-700"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Code'}</span>
            </button>

            <button
              onClick={handleDownloadSingle}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-300 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg transition-colors border border-slate-700"
              title="Download active file"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

        {/* Code Content Viewport */}
        <div className="flex-1 overflow-auto bg-[#070A11] p-4 text-xs font-mono leading-relaxed select-text">
          <pre className="text-slate-300">
            <code>{activeCode}</code>
          </pre>
        </div>

        {/* Modal Footer with 1-Click ZIP Download */}
        <div className="px-6 py-3.5 border-t border-slate-800 bg-slate-950/80 flex items-center justify-between shrink-0">
          <div className="text-xs text-slate-400 flex items-center gap-2">
            <span>Includes: <code className="text-slate-300">ui.h</code>, <code className="text-slate-300">ui.c</code>, <code className="text-slate-300">ui_events.c</code>, <code className="text-slate-300">main.ino</code>, <code className="text-slate-300">platformio.ini</code>, <code className="text-slate-300">README.md</code></span>
          </div>

          <div className="flex items-center gap-3">
            <button
              onClick={onClose}
              className="px-4 py-2 text-xs font-medium text-slate-400 hover:text-white cursor-pointer"
            >
              Close
            </button>
            <button
              onClick={handleDownloadZip}
              disabled={isZipping}
              className="flex items-center gap-2 px-4 py-2 text-xs font-semibold text-slate-950 bg-cyan-400 hover:bg-cyan-300 rounded-lg transition-colors shadow-sm cursor-pointer disabled:opacity-50"
            >
              <FolderArchive className="w-4 h-4" />
              <span>{isZipping ? 'Bundling ZIP...' : 'Download Project Package (.ZIP)'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
